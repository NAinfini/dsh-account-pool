export type Translate = (key: CopyKey, vars?: Record<string, string | number>) => string

/** Dictionary-backed translator; `{name}` placeholders are replaced from `vars`. */
export function translator(dictionary: Record<CopyKey, string>): Translate {
  return (key, vars) => {
    const text = dictionary[key]
    if (vars === undefined) return text
    return text.replace(/\{(\w+)\}/g, (whole, name: string) => (vars[name] === undefined ? whole : String(vars[name])))
  }
}

/** Pick the dictionary for a language tag; Chinese tags get zh, everything else en. */
export function dictionaryFor(language: string | undefined): Record<CopyKey, string> {
  return language !== undefined && language.toLowerCase().startsWith('zh') ? zh : en
}
